CLASSES = ["akiec", "bcc", "bkl", "df", "mel", "nv", "vasc"]
CLASS_TO_IDX = {c: i for i, c in enumerate(CLASSES)}


def generate_comparison_report(metrics_data: Dict, output_md: str = "reports/model_comparison.md"):
    m = metrics_data.get("metrics", {})
    cm = m.get("confusion_matrix", [])

    md_lines = [
        "# DermAI: Model Evaluation & Benchmark Comparison Report",
        "",
        "> **Regulatory & Clinical Notice**: AI-assisted analysis, not a standalone medical diagnosis. DermAI is an automated screening and clinical decision support system, not an autonomous medical device.",
        "",
        "---",
        "",
        "## 1. Evaluated Architecture",
        f"- **Model Architecture**: `{metrics_data.get('model_name', 'efficientnet_b0')}`",
        f"- **Timm Backbone**: `{metrics_data.get('timm_name', 'efficientnet_b0')}`",
        f"- **Version Tag**: `{metrics_data.get('version_tag', 'v1.0-efficientnet_b0')}`",
        f"- **Evaluation Mode**: `{'Smoke Mode (CPU 200 samples)' if metrics_data.get('smoke_mode') else 'Full Test Set (1,502 images)'}`",
        f"- **Evaluation Date**: `{metrics_data.get('evaluated_at', datetime.utcnow().isoformat())}`",
        "",
        "## 2. Core Quantitative Metrics",
        "",
        "| Metric | Score | Clinical / Technical Significance |",
        "|---|---|---|",
        f"| **Overall Accuracy** | **{m.get('accuracy', 0.0):.4f}** | General classification rate across all evaluated samples |",
        f"| **Balanced Accuracy** | **{m.get('balanced_accuracy', 0.0):.4f}** | Unweighted average recall; accounts for extreme HAM10000 class imbalance |",
        f"| **Macro Precision** | **{m.get('macro_precision', 0.0):.4f}** | Average precision across all 7 lesion categories |",
        f"| **Macro Recall (Sensitivity)** | **{m.get('macro_recall', 0.0):.4f}** | Average detection sensitivity across all classes |",
        f"| **Macro F1-Score** | **{m.get('macro_f1', 0.0):.4f}** | Harmonic mean of macro precision and recall |",
        f"| **Matthews Correlation (MCC)** | **{m.get('matthews_corrcoef', 0.0):.4f}** | Balanced correlation metric robust to severe skewness |",
        "",
        "## 3. Confusion Matrix",
        "",
        "| Ground Truth \\ Predicted | " + " | ".join(CLASSES) + " |",
        "|---|" + "|".join(["---"] * len(CLASSES)) + "|",
    ]

    for i, row in enumerate(cm):
        row_str = f"| **{CLASSES[i]}** | " + " | ".join(str(val) for val in row) + " |"
        md_lines.append(row_str)

    md_lines.extend([
        "",
        "## 4. Viva / Defense Summary",
        "1. **Imbalance Handling**: Class weights are applied to the Cross-Entropy loss so rare classes (melanoma, dermatofibroma) receive higher gradient penalties.",
        "2. **Zero Leakage**: Train, validation, and test sets are strictly partitioned by `lesion_id`, ensuring multiple photos of the same lesion never cross splits.",
        "3. **Clinical Priority**: For medical screening, sensitivity on malignant lesions (melanoma, basal cell carcinoma) takes precedence over overall accuracy.",
        "",
        "---",
        "**Report Generated By**: DermAI Evaluation Suite (`ml/evaluate.py`)"
    ])

    Path(output_md).parent.mkdir(parents=True, exist_ok=True)
    with open(output_md, "w", encoding="utf-8") as f:
        f.write("\n".join(md_lines) + "\n")
    print(f"[REPORT] Saved model comparison report to {output_md}")


def main():
    parser = argparse.ArgumentParser(description="Evaluate DermAI Model")
    parser.add_argument("--metrics-path", default="models/metrics.json")
    parser.add_argument("--output-report", default="reports/model_comparison.md")
    args = parser.parse_args()

    if not os.path.exists(args.metrics_path):
        print(f"[EVAL ERROR] Metrics file not found at {args.metrics_path}. Please train a model first.")
        return

    with open(args.metrics_path, "r", encoding="utf-8") as f:
        data = json.load(f)

    generate_comparison_report(data, args.output_report)


if __name__ == "__main__":
    main()
